
//Example of Function with name

function greet(name) {
    return "Hello, " + name + "!";
}   

console.log(greet("Alice")); // Output: Hello, Alice!

// Example of Anonymous Function assigned to a variable
const sayGoodbye = function(name) {
    return "Goodbye, " + name + "!";
};
console.log(sayGoodbye("Alice")); // Output: Goodbye, Alice!